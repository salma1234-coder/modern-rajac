// 🚀 تشغيل السكريبت
// ============================================

async function addStudents() {
    const dbPath = path.join(__dirname, 'database.json');
    
    // قراءة قاعدة البيانات
    let db;
    try {
        const data = fs.readFileSync(dbPath, 'utf8');
        db = JSON.parse(data);
    } catch (error) {
        console.log('إنشاء قاعدة بيانات جديدة...');
        db = { users: [], loginRecords: [] };
    }
    
    if (!db.users) db.users = [];
    if (!db.loginRecords) db.loginRecords = [];
    
    console.log(`\n📚 إضافة ${studentsToAdd.length} طالب...\n`);
    
    let added = 0;
    let skipped = 0;
    const passwordsList = [];
    
    for (const student of studentsToAdd) {
        // التحقق من وجود اسم المستخدم
        if (db.users.find(u => u.username === student.username)) {
            console.log(`⚠️  تم تخطي ${student.username} - موجود بالفعل`);
            skipped++;
            continue;
        }
        
        // تشفير كلمة المرور
        const hashedPassword = await bcrypt.hash(student.password, 10);
        
        // إنشاء المستخدم
        const newUser = {
            id: Date.now().toString() + Math.random().toString(36).substr(2, 9),
            username: student.username,
            password: hashedPassword,
            fullName: student.fullName,
            grade: student.grade,
            gender: student.gender,
            className: student.className,
            role: 'student',
            createdAt: new Date().toISOString()
        };
        
        db.users.push(newUser);
        added++;
        
        // حفظ كلمة المرور للطباعة
        passwordsList.push({
            username: student.username,
            password: student.password,
            fullName: student.fullName,
            grade: student.grade,
            className: student.className
        });
        
        console.log(`✅ تم إضافة: ${student.username} - ${student.fullName}`);
    }
    
    // حفظ قاعدة البيانات
    fs.writeFileSync(dbPath, JSON.stringify(db, null, 2));
    
    console.log(`\n📊 النتائج:`);
    console.log(`✅ تم إضافة: ${added} طالب`);
    console.log(`⚠️  تم تخطي: ${skipped} طالب`);
    
    // طباعة كلمات المرور
    console.log(`\n🔑 كلمات المرور:\n`);
    console.log('اسم المستخدم | كلمة المرور | الاسم الكامل | الصف | الفصل');
    console.log(''.padEnd(80, '-'));
    
    passwordsList.forEach(s => {
        const gradeName = s.grade === 'first' ? 'الأول' : 
                          s.grade === 'second' ? 'الثاني' : 'الثالث';
        console.log(`${s.username.padEnd(15)} | ${s.password.padEnd(15)} | ${s.fullName.padEnd(20)} | ${gradeName} | ${s.className}`);
    });
    
    // حفظ كلمات المرور في ملف CSV
    let csvContent = 'اسم المستخدم,كلمة المرور,الاسم الكامل,الصف,الفصل\n';
    passwordsList.forEach(s => {
        const gradeName = s.grade === 'first' ? 'الأول' : 
                          s.grade === 'second' ? 'الثاني' : 'الثالث';
        csvContent += `${s.username},${s.password},${s.fullName},${gradeName},${s.className}\n`;
    });
    
    const csvPath = path.join(__dirname, 'passwords.csv');
    fs.writeFileSync(csvPath, csvContent);
    console.log(`\n📥 تم حفظ كلمات المرور في: passwords.csv`);
    
    console.log(`\n✅ تم الانتهاء!`);
}

// تشغيل السكريبت
addStudents().catch(error => {
    console.error('❌ خطأ:', error);
    process.exit(1);
});
